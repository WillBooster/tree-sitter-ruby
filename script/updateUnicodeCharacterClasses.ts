import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';

const version = '17.0.0';
const root = path.resolve(import.meta.dirname, '..');
const points = new Set<number>();
const [derived, unicode] = await Promise.all(
  ['DerivedCoreProperties.txt', 'UnicodeData.txt'].map(async (name) => {
    const response = await fetch(`https://www.unicode.org/Public/${version}/ucd/${name}`);
    assert.ok(response.ok, `${name}: ${response.status}`);
    return response.text();
  })
);
for (const line of derived!.split('\n')) {
  const [range, property] = line
    .split('#')[0]!
    .split(';')
    .map((part) => part.trim());
  if (property !== 'Uppercase') continue;
  const [first, last = first] = range!.split('..').map((value) => Number.parseInt(value, 16));
  for (let point = first!; point <= last!; point++) points.add(point);
}
for (const line of unicode!.split('\n')) {
  const [point, , category] = line.split(';');
  if (category === 'Lt') points.add(Number.parseInt(point!, 16));
}
const excluded = new Set(Array.from({ length: 33 }, (_, point) => point));
for (const character of ':;`"\'@$#.,|^&<=>+-*/\\%?!~()[]{}') excluded.add(character.codePointAt(0)!);
const uppercase = toRanges(points);
const excludedIdentifier = toRanges(excluded);
fs.writeFileSync(
  path.join(root, 'src/unicodeCharacterClasses.json'),
  JSON.stringify({ version, uppercase, excludedIdentifier }) + '\n'
);
fs.writeFileSync(
  path.join(root, 'src/unicode_character_classes.h'),
  `// Unicode ${version} Uppercase + Lt and identifier delimiters, generated by script/updateUnicodeCharacterClasses.ts.
// Unicode data: https://www.unicode.org/terms_of_use.html
#ifndef RUBY_UNICODE_CHARACTER_CLASSES_H_
#define RUBY_UNICODE_CHARACTER_CLASSES_H_

#include <stdbool.h>
#include <stdint.h>

static inline bool ruby_in_character_ranges(int32_t codepoint, const int32_t ranges[][2], unsigned count) {
    unsigned left = 0;
    unsigned right = count;
    while (left < right) {
        unsigned middle = left + (right - left) / 2;
        if (codepoint < ranges[middle][0]) right = middle;
        else if (codepoint > ranges[middle][1]) left = middle + 1;
        else return true;
    }
    return false;
}

${renderClass('ruby_unicode_uppercase', uppercase)}
${renderClass('ruby_identifier_character', excludedIdentifier, true)}
#endif
`
);

function toRanges(points: Set<number>): [number, number][] {
  const ranges: [number, number][] = [];
  for (const point of [...points].toSorted((left, right) => left - right)) {
    const last = ranges.at(-1);
    if (last && last[1] + 1 === point) last[1] = point;
    else ranges.push([point, point]);
  }
  return ranges;
}

function renderClass(name: string, ranges: [number, number][], negate = false): string {
  return `static inline bool ${name}(int32_t codepoint) {
    static const int32_t ranges[][2] = {
${ranges.map(([first, last]) => `        {0x${first.toString(16)}, 0x${last.toString(16)}}`).join(',\n')}
    };
    return ${negate ? '!' : ''}ruby_in_character_ranges(codepoint, ranges, sizeof(ranges) / sizeof(ranges[0]));
}
`;
}
